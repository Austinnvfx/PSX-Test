/// <summary>
/// 5x7 pixel font (with 2-pixel descenders) for the PSX HUD: tooltips, the phone, documents, titles.
/// Each character is 6 pixels wide including spacing; a line is 10 pixels tall at scale 1.
/// </summary>
public static class PSXFont
{
    public const int Advance = 6, GlyphHeight = 9, LineHeight = 10;

    /// <summary>Width in pixels of <paramref name="s"/> at <paramref name="scale"/>.</summary>
    public static int Measure(string s, int scale = 1) => string.IsNullOrEmpty(s) ? 0 : (s.Length * Advance - 1) * scale;

    public static bool Has(char c) => Glyphs.ContainsKey(c);

    /// <summary>Draw text into a top-down pixel buffer. (x, y) is the top-left corner.</summary>
    public static void Draw(Color32[] buf, int w, int h, int x, int y, string s, Color32 color, int scale = 1, RectInt? clip = null)
    {
        if (string.IsNullOrEmpty(s)) return;
        int cx = x;
        foreach (char ch in s)
        {
            if (!Glyphs.TryGetValue(ch, out var g)) g = Glyphs['?'];
            for (int row = 0; row < GlyphHeight; row++)
            {
                byte bits = g[row];
                if (bits == 0) continue;
                for (int col = 0; col < 5; col++)
                {
                    if ((bits & (0x10 >> col)) == 0) continue;
                    for (int sy = 0; sy < scale; sy++)
                    for (int sx = 0; sx < scale; sx++)
                        {
                            int px = cx + col * scale + sx, py = y + row * scale + sy;
                            if (clip.HasValue && !clip.Value.Contains(new Vector2Int(px, py))) continue;
                            Blend(buf, w, h, px, py, color);
                        }
                }
            }
            cx += Advance * scale;
        }
    }

    static void Blend(Color32[] buf, int w, int h, int x, int y, Color32 c)
    {
        if (x < 0 || y < 0 || x >= w || y >= h) return;
        int i = (h - 1 - y) * w + x; // texture rows go bottom-up
        if (c.a == 255) { buf[i] = c; return; }
        var d = buf[i];
        float a = c.a / 255f, ia = 1f - a;
        buf[i] = new Color32((byte)(c.r * a + d.r * ia), (byte)(c.g * a + d.g * ia), (byte)(c.b * a + d.b * ia),
                             (byte)Mathf.Min(255, c.a + d.a * ia));
    }

    /// <summary>Word-wrap to lines of at most <paramref name="maxChars"/> characters. Keeps blank lines.</summary>
    public static List<string> Wrap(string text, int maxChars)
    {
        var lines = new List<string>();
        if (text == null) return lines;
        foreach (var para in text.Replace("\r", "").Split('\n'))
        {
            var line = new StringBuilder();
            foreach (var word in para.Split(' '))
            {
                string wd = word;
                while (wd.Length > maxChars) // words longer than a line get split
                {
                    if (line.Length > 0) { lines.Add(line.ToString()); line.Clear(); }
                    lines.Add(wd.Substring(0, maxChars));
                    wd = wd.Substring(maxChars);
                }
                int need = line.Length == 0 ? wd.Length : line.Length + 1 + wd.Length;
                if (need > maxChars) { lines.Add(line.ToString()); line.Clear(); }
                if (line.Length > 0) line.Append(' ');
                line.Append(wd);
            }
            lines.Add(line.ToString());
        }
        return lines;
    }

